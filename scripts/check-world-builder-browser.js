// Run through playwright-cli run-code --filename on a built/served app.
async (page) => {
  const browser = await page.evaluate(() => navigator.userAgent.includes('Edg/') ? 'edge' : 'chrome');
  const output = `output/playwright/world-builder-${browser}`;
  const checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, ok) => { checks.push({ name, passed: !!ok }); if (!ok) throw new Error(name); };
  const button = name => page.getByRole('button', { name, exact: true });
  const input = name => page.getByLabel(name, { exact: true });
  if (await button('Enter the world').isVisible()) await button('Enter the world').click();
  await page.waitForFunction(() => !!window.__MUSIC_UNIVERSE_WORLD_E2E__ && !!window.__MUSIC_UNIVERSE_E2E__);
  if (!await button('Close project editor').isVisible()) await button('Open project editor').click();
  const region = page.getByRole('region', { name: 'World builder', exact: true });
  const drafts = page.getByRole('list', { name: 'Active project drafts', exact: true }).locator(':scope > li');
  const count = await drafts.count();
  const exportProject = async () => {
    const pending = page.waitForEvent('download');
    await button('Export project').click();
    const stream = await (await pending).createReadStream();
    let json = ''; for await (const chunk of stream) json += chunk.toString();
    return JSON.parse(json);
  };
  const before = await exportProject();
  check('complete Memory Journey template is selected', await input('Memory Journey template').isChecked());
  check('approved gate alternatives are offered', await input('World gate asset').locator('option').count() === 3);
  await input('New world name').fill(' ');
  await button('Build world from template').click();
  await region.getByRole('alert').waitFor();
  check('empty title preserves the current project', (await exportProject()).id === before.id && await drafts.count() === count);
  await input('New world name').fill('Builder acceptance planet');
  await input('World gate asset').selectOption('departure-portal');
  await button('Preview selected world asset').click();
  await input('Selected gate model preview').locator('canvas').waitFor();
  await page.waitForTimeout(1200);
  await region.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/asset-preview.png` });
  check('selected model has a visual preview', await input('Selected gate model preview').locator('canvas').isVisible());
  await button('Preview selected world asset').click();
  const modelRoute = '**/assets/generated/support-terminal*.glb';
  await page.route(modelRoute, route => route.fulfill({ status: 404, body: 'Missing model' }));
  await button('Build world from template').click();
  await region.getByRole('alert').waitFor();
  check('missing model blocks creation with an error', await region.getByRole('alert').isVisible() && (await exportProject()).id === before.id && await drafts.count() === count);
  await page.unroute(modelRoute);
  let release;
  const delayed = new Promise(resolve => { release = resolve; });
  await page.route(modelRoute, async route => { await delayed; await route.continue().catch(() => {}); });
  await button('Build world from template').click();
  await button('Cancel world build').waitFor();
  await button('Cancel world build').click(); release();
  await button('Build world from template').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('[aria-label="Cancel world build"]'));
  check('cancel preserves draft and allows retry', (await exportProject()).id === before.id && await button('Build world from template').isEnabled());
  await page.unroute(modelRoute);
  await button('Build world from template').click();
  await button('Close project editor').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => window.__MUSIC_UNIVERSE_WORLD_E2E__?.getSnapshot().interactions.find(item => item.id === 'departure-gate')?.loadedAssetUrl?.includes('departure-portal'));
  check('creation enters the world with the selected model actually loaded', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().interactions.find(item => item.id === 'departure-gate').loadedAssetUrl.includes('departure-portal')));
  check('selected gate keeps its reviewed pass-through collision', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().interactions.find(item => item.id === 'departure-gate').collider.type === 'none'));
  await page.screenshot({ path: `${output}/arrival.png` });
  await button('Open project editor').click();
  const project = await exportProject();
  check('new world is a separate local draft', await drafts.count() === count + 1 && project.id !== before.id && project.metadata.title === 'Builder acceptance planet');
  check('all four roles have persisted model selections', project.scene.objects.every(object => typeof object.appearance.assetId === 'string'));
  check('gate choice and license are in project data', project.scene.objects.find(object => object.id === 'departure-gate').appearance.assetId === 'departure-portal' && project.assets.find(asset => asset.id === 'departure-portal').licenseRef === 'MIT');
  const invalid = structuredClone(project); invalid.scene.objects.find(object => object.id === 'departure-gate').appearance.assetId = 'product-tower-hangar';
  const importProject = async json => input('Import MusicWorldProject').evaluate((el, json) => {
    const transfer = new DataTransfer(); transfer.items.add(new File([json], 'world.musicworld.json', { type: 'application/json' }));
    el.files = transfer.files; el.dispatchEvent(new Event('change', { bubbles: true }));
  }, JSON.stringify(json));
  await importProject(invalid);
  check('incompatible model import preserves the active world', (await exportProject()).id === project.id);
  await page.waitForTimeout(900);
  await page.reload();
  await button('Open project editor').click();
  check('refresh restores selected models', (await exportProject()).scene.objects.find(object => object.id === 'departure-gate').appearance.assetId === 'departure-portal');
  await importProject(project);
  check('project changes retain exactly one builder', await region.count() === 1);
  await page.waitForFunction(() => window.__MUSIC_UNIVERSE_WORLD_E2E__?.getSnapshot().interactions.every(item => typeof item.loadedAssetUrl === 'string'));
  check('reimport reloads all selected models', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().interactions.every(item => typeof item.loadedAssetUrl === 'string')));
  check('valid reimport reconstructs selected gate', (await exportProject()).scene.objects.find(object => object.id === 'departure-gate').appearance.assetId === 'departure-portal');
  await input('New world name').focus(); await page.keyboard.press('Tab');
  check('keyboard reaches asset selection', await input('World gate asset').evaluate(el => el === document.activeElement));
  await page.setViewportSize({ width: 800, height: 600 });
  await region.scrollIntoViewIfNeeded();
  check('builder fits compact layout', await region.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth; }));
  await page.screenshot({ path: `${output}/compact.png` });
  await button('Close project editor').click();
  await button('Toggle reduced visual effects').click();
  await button('Open project editor').click();
  check('builder works with reduced effects', await button('Build world from template').isEnabled());
  await button('Close project editor').click();
  await page.locator('#music-file-input').setInputFiles('output/playwright/music-analysis-energy-change.wav');
  await button('Play').waitFor();
  const seek = async seconds => page.getByRole('slider', { name: 'Music progress', exact: true }).evaluate((el, seconds) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, String(seconds));
    el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true }));
  }, seconds);
  const place = async position => {
    await page.evaluate(position => {
      const radius = window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().planetRadius;
      const [x, h, z] = position, distance = Math.hypot(x, z);
      const scale = distance ? Math.sin(distance / radius) * (radius + h) / distance : 1;
      window.__MUSIC_UNIVERSE_E2E__.setPlayerTransform([x * scale, Math.cos(distance / radius) * (radius + h) - radius, z * scale], Math.PI);
    }, position);
    await page.waitForTimeout(500);
  };
  await place([0, .65, -3]);
  check('built world guide starts journey', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.triggerInteraction('npc-guide')));
  await button('Close dialog').click();
  await place([-2, .65, -11]);
  check('archive interaction is reachable outside the solid model', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.triggerInteraction('memory-archive')));
  await button('Close dialog').click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${output}/archive.png` });
  await button('Play').click(); await seek(54); await button('Pause').click();
  await place([0, .65, -13]);
  check('selected gate completes the built world', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.triggerInteraction('departure-gate')));
  await page.waitForFunction(() => window.__MUSIC_UNIVERSE_WORLD_E2E__?.getSnapshot().flags['journey.completed'] === true);
  check('full template journey reaches completion', await page.evaluate(() => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().currentObjectiveId === null));
  await page.waitForTimeout(600);
  check('completion dialog stays above the audio player on compact screens', await page.getByRole('dialog').evaluate(el => {
    const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.left + 24, r.bottom - 32));
  }));
  await page.screenshot({ path: `${output}/completed.png` });
  await button('Close dialog').click();
  await seek(0); await button('Play').click();
  check('built world can restart music from the beginning', await button('Pause').isVisible());
  await button('Pause').click();
  await button('Open project editor').click();
  check('original draft remains available', await button(`Open project ${before.metadata.title}`).count() >= 1);
  check('no unhandled page errors', errors.length === 0);
  const report = { status: 'passed', browser, checks, errors };
  const pending = page.waitForEvent('download');
  await page.evaluate(report => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' }));
    const link = document.createElement('a'); link.href = url; link.download = 'world-builder-report.json'; link.click(); setTimeout(() => URL.revokeObjectURL(url), 1000);
  }, report);
  await (await pending).saveAs(`${output}/report.json`);
  return report;
}
