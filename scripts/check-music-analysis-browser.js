// Run through playwright-cli run-code --filename on a built/served app.
async (page) => {
  const browser = await page.evaluate(() => navigator.userAgent.includes('Edg/') ? 'edge' : 'chrome');
  const output = `output/playwright/music-analysis-${browser}`;
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, ok) => { checks.push({ name, passed: !!ok }); if (!ok) throw new Error(name); };
  const button = name => page.getByRole('button', { name, exact: true });
  const enter = button('Enter the world');
  if (await enter.isVisible()) await enter.click();
  if (await button('Close project editor').isVisible()) await button('Close project editor').click();
  await page.waitForFunction(() => !!window.__MUSIC_UNIVERSE_WORLD_E2E__);
  await button('Open project editor').click();
  await button('Create project').click();
  await button('Close project editor').click();
  const fixturePath = 'output/playwright/music-analysis-energy-change.wav';
  await page.locator('#music-file-input').setInputFiles(fixturePath);
  await button('Play').waitFor();
  await button('Open project editor').click();
  const analyze = button('Analyze loaded music');
  check('loaded song can be analyzed', await analyze.isEnabled());
  const started = Date.now();
  await analyze.click();
  const rows = page.getByRole('list', { name: 'Editable music sections' }).locator(':scope > li');
  await rows.nth(1).waitFor({ timeout: 30000 });
  await page.waitForFunction(() => !document.querySelector('[aria-label="Cancel music analysis"]'));
  const analysisMs = Date.now() - started;
  check('sustained level change produces two candidate sections', await rows.count() === 2);
  check('analysis completes within desktop budget', analysisMs < 10000);
  check('waveform is accessible', await page.getByRole('img', { name: 'Song waveform and relative loudness' }).isVisible());
  check('boundary is around 30 seconds', Math.abs(Number(await page.getByLabel('Section 2 start seconds', { exact: true }).inputValue()) - 30) < 1);
  await page.getByLabel('Section 2 name', { exact: true }).fill('Chorus');
  await page.getByLabel('Section 2 start seconds', { exact: true }).fill('36');
  await button('Apply section 2').click();
  check('save retains keyboard focus', await button('Apply section 2').evaluate(element => element === document.activeElement));
  check('boundary edit saved', Number(await page.getByLabel('Section 2 start seconds', { exact: true }).inputValue()) === 36);
  await button('Undo project edit').click();
  await page.waitForFunction(() => Math.abs(Number(document.querySelector('[aria-label="Section 2 start seconds"]')?.value) - 30) < 1);
  const undoBoundary = Number(await page.getByLabel('Section 2 start seconds', { exact: true }).inputValue());
  check(`undo restores suggested boundary (${undoBoundary})`, Math.abs(undoBoundary - 30) < 1);
  await button('Redo project edit').click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Section 2 name"]')?.value === 'Chorus');
  check('redo restores label', await page.getByLabel('Section 2 name', { exact: true }).inputValue() === 'Chorus');
  await page.getByLabel('Section 2 start seconds', { exact: true }).fill('-1');
  await button('Apply section 2').click();
  check('invalid boundary is explained', await rows.nth(1).getByRole('alert').isVisible());
  await page.getByLabel('Section 2 start seconds', { exact: true }).fill('36');
  await button('Apply section 2').click();
  await button('Split section 2').click();
  check('split adds a section', await rows.count() === 3);
  await button('Merge section 3').click();
  check('merge removes a boundary', await rows.count() === 2);
  await page.getByLabel('Timeline cue', { exact: true }).selectOption('weather-front');
  await button('Place cue at section 2').click();
  await page.waitForFunction(() => Number(document.querySelector('[aria-label="Timeline cue normalized position"]')?.value) === .6);
  check('existing world cue moves to section start', Number(await page.getByLabel('Timeline cue normalized position', { exact: true }).inputValue()) === .6);
  await button('Preview section 2').click();
  check('preview seeks authoritative audio', Math.abs(Number(await page.getByRole('slider', { name: 'Music progress', exact: true }).inputValue()) - 36) < .3);
  await page.getByRole('region', { name: 'Local music analysis' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/sections.png` });
  const exportProject = async () => {
    const pending = page.waitForEvent('download');
    await button('Export project').click();
    const download = await pending;
    const stream = await download.createReadStream();
    let json = ''; for await (const chunk of stream) json += chunk.toString();
    return JSON.parse(json);
  };
  const exported = await exportProject();
  check('analysis and edited sections export', exported.track.analysis.sections[1].label === 'Chorus' && exported.track.analysis.sections[1].start === .6);
  const invalid = structuredClone(exported); invalid.track.analysis.sections[1].start = 0;
  await page.getByLabel('Import MusicWorldProject', { exact: true }).evaluate((input, json) => {
    const transfer = new DataTransfer(); transfer.items.add(new File([json], 'bad.json', { type: 'application/json' }));
    input.files = transfer.files; input.dispatchEvent(new Event('change', { bubbles: true }));
  }, JSON.stringify(invalid));
  check('malformed analysis import preserves existing project', JSON.stringify((await exportProject()).track.analysis) === JSON.stringify(exported.track.analysis));
  await page.waitForTimeout(900);
  await page.reload();
  await button('Open project editor').click();
  await page.getByLabel('Section 2 name', { exact: true }).waitFor();
  check('refresh restores saved analysis', await page.getByLabel('Section 2 name', { exact: true }).inputValue() === 'Chorus');
  check('saved analysis can be edited before reattaching song', await button('Apply section 2').isEnabled());
  check('analysis waits for the original song', await analyze.isDisabled());
  await button('Close project editor').click();
  await page.getByLabel('Restore original project song', { exact: true }).setInputFiles(fixturePath);
  await button('Play').waitFor();
  await button('Play').click();
  await page.waitForTimeout(300);
  await button('Pause').click();
  await button('Open project editor').click();
  check('matching reattachment keeps edited sections', await page.getByLabel('Section 2 name', { exact: true }).inputValue() === 'Chorus');
  await page.evaluate(() => {
    window.__originalAnalysisWorker = window.Worker;
    window.Worker = class extends window.__originalAnalysisWorker {
      postMessage(...args) { this.delay = window.setTimeout(() => super.postMessage(...args), 2000); }
      terminate() { window.clearTimeout(this.delay); super.terminate(); }
    };
  });
  await analyze.click();
  await button('Cancel music analysis').click();
  await page.evaluate(() => { window.Worker = window.__originalAnalysisWorker; delete window.__originalAnalysisWorker; });
  check('cancel retains saved sections', await rows.count() === 2 && await page.getByLabel('Section 2 name', { exact: true }).inputValue() === 'Chorus');
  check('canceled job resets button', await analyze.isEnabled());
  await page.evaluate(() => { window.__originalAnalysisWorker = window.Worker; window.Worker = class { constructor() { throw new Error('Simulated worker failure'); } }; });
  await analyze.click();
  await page.getByRole('region', { name: 'Local music analysis' }).getByRole('alert').waitFor();
  check('worker failure preserves saved analysis', await page.getByLabel('Section 2 name', { exact: true }).inputValue() === 'Chorus');
  await page.evaluate(() => { window.Worker = window.__originalAnalysisWorker; delete window.__originalAnalysisWorker; });
  await analyze.click();
  await page.waitForFunction(() => !document.querySelector('[aria-label="Cancel music analysis"]'));
  check('retry recovers after worker failure', await page.getByRole('region', { name: 'Local music analysis' }).getByRole('alert').count() === 0);
  await button('Close project editor').click();
  await page.locator('#music-file-input').setInputFiles('output/playwright/music-analysis-replacement.wav');
  await button('Play').waitFor();
  await button('Open project editor').click();
  check('replacement clears old-song analysis', await page.getByRole('list', { name: 'Editable music sections' }).count() === 0);
  check('no unhandled browser errors', errors.length === 0);
  const report = { status: 'passed', analysisMs, checks, errors, screenshots: [`${output}/sections.png`] };
  const reportDownload = page.waitForEvent('download');
  await page.evaluate(report => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' }));
    const link = document.createElement('a'); link.href = url; link.download = 'analysis-report.json'; link.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  }, report);
  await (await reportDownload).saveAs(`${output}/report.json`);
  return report;
}
