// Run through playwright-cli run-code --filename on a built/served app.
async (page) => {
  const browser = await page.evaluate(() => navigator.userAgent.includes('Edg/') ? 'edge' : 'chrome');
  const output = `output/playwright/music-tempo-${browser}`;
  const checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, ok) => { checks.push({ name, passed: !!ok }); if (!ok) throw new Error(name); };
  const button = name => page.getByRole('button', { name, exact: true });
  const input = name => page.getByLabel(name, { exact: true });
  if (await button('Enter the world').isVisible()) await button('Enter the world').click();
  await page.waitForFunction(() => !!window.__MUSIC_UNIVERSE_WORLD_E2E__);
  if (!await button('Close project editor').isVisible()) await button('Open project editor').click();
  await button('Create project').click();
  await button('Close project editor').click();
  await page.locator('#music-file-input').setInputFiles('output/playwright/music-analysis-energy-change.wav');
  await button('Play').waitFor();
  await button('Play').click();
  await button('Open project editor').click();
  const region = page.getByRole('region', { name: 'Music tempo editing', exact: true });
  const exportProject = async () => {
    const pending = page.waitForEvent('download');
    await button('Export project').click();
    const stream = await (await pending).createReadStream();
    let json = ''; for await (const chunk of stream) json += chunk.toString();
    return JSON.parse(json);
  };
  check('alignment waits for confirmed tempo', await button('Snap selected cue to beat').isDisabled());
  await input('Tempo BPM').fill('0');
  await button('Save music tempo').click();
  check('invalid tempo has actionable error', await region.getByRole('alert').isVisible());
  check('invalid input preserves project', (await exportProject()).track.tempo === undefined);
  await input('Tempo BPM').fill('120');
  await input('Tempo first beat seconds').fill('60');
  await button('Save music tempo').click();
  check('first beat cannot start at song end', await region.getByRole('alert').isVisible());
  await input('Tempo first beat seconds').fill('0.25');
  await button('Save music tempo').click();
  check('save preserves button focus', await button('Save music tempo').evaluate(el => el === document.activeElement));
  check('editing tempo keeps music playing', await button('Pause').isVisible());
  await button('Toggle tempo audition').click();
  check('editor can pause music for tempo editing', await button('Play').isVisible());
  await button('Toggle tempo audition').click();
  check('editor can resume music for tapping', await button('Pause').isVisible());
  let project = await exportProject();
  check('confirmed tempo exports', project.track.tempo.bpm === 120 && project.track.tempo.offsetSeconds === .25 && project.track.tempo.source === 'manual');
  await input('Timeline cue').selectOption('weather-front');
  await button('Snap selected cue to beat').click();
  project = await exportProject();
  check('selected world cue snaps to exact beat', project.timeline.cues.find(c => c.id === 'weather-front').position === 20.25 / 60);
  await button('Undo project edit').click();
  check('undo restores cue position', (await exportProject()).timeline.cues.find(c => c.id === 'weather-front').position === .34);
  await button('Redo project edit').click();
  check('redo restores beat alignment', (await exportProject()).timeline.cues.find(c => c.id === 'weather-front').position === 20.25 / 60);
  const sky = project.timeline.cues.find(c => c.id === 'weather-front').actions.find(a => a.type === 'set-environment').payload.skyColor;
  await button('Close project editor').click();
  await button('Pause').click();
  const seek = async seconds => {
    await page.getByRole('slider', { name: 'Music progress', exact: true }).evaluate((el, seconds) => {
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, String(seconds));
      el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true }));
    }, seconds);
  };
  await seek(21);
  await page.waitForFunction(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor === sky, sky);
  check('forward seek applies aligned world cue', await page.evaluate(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor === sky, sky));
  await seek(19);
  await page.waitForFunction(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor !== sky, sky);
  check('backward seek restores state before aligned cue', await page.evaluate(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor !== sky, sky));
  await seek(21);
  await page.waitForFunction(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor === sky, sky);
  check('repeated seek reconstructs aligned cue', await page.evaluate(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor === sky, sky));
  await seek(0); await button('Play').click();
  check('restart from beginning keeps initial world state', await button('Pause').isVisible() && await page.evaluate(sky => window.__MUSIC_UNIVERSE_WORLD_E2E__.getSnapshot().environment.skyColor !== sky, sky));
  await button('Open project editor').click();
  await button('Double tempo').click();
  check('unsaved tempo prevents alignment', await button('Snap selected cue to beat').isDisabled());
  check('double control updates draft', Number(await input('Tempo BPM').inputValue()) === 240);
  await button('Halve tempo').click();
  check('half control restores draft', Number(await input('Tempo BPM').inputValue()) === 120);
  await button('Clear music tempo').click();
  check('clear removes tempo and keeps cue', (await exportProject()).track.tempo === undefined && (await exportProject()).timeline.cues.find(c => c.id === 'weather-front').position === 20.25 / 60);
  await button('Undo project edit').click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Tempo BPM"]')?.value === '120');
  check('undo restores cleared tempo', (await exportProject()).track.tempo.bpm === 120);
  await button('Reset tempo taps').click();
  for (let i = 0; i < 4; i++) { await button('Tap tempo').click(); if (i < 3) await page.waitForTimeout(500); }
  const tapped = Number(await input('Tempo BPM').inputValue());
  check('tapping produces editable BPM suggestion', tapped > 90 && tapped < 140 && await button('Snap selected cue to beat').isDisabled());
  await button('Save music tempo').click();
  check('tap provenance saved after confirmation', (await exportProject()).track.tempo.source === 'tap');
  await input('Tempo BPM').fill('120');
  await button('Save music tempo').click();
  await button('Use playhead as first beat').click();
  check('playhead can set first beat', Number(await input('Tempo first beat seconds').inputValue()) > 0);
  await input('Tempo first beat seconds').fill('0.25');
  await button('Save music tempo').click();
  await button('Analyze loaded music').click();
  await page.getByRole('list', { name: 'Editable music sections' }).waitFor();
  check('waveform analysis retains saved tempo', (await exportProject()).track.tempo.bpm === 120);
  const saved = await exportProject();
  const invalid = structuredClone(saved); invalid.track.tempo.source = 'automatic';
  await input('Import MusicWorldProject').evaluate((el, json) => {
    const transfer = new DataTransfer(); transfer.items.add(new File([json], 'invalid-tempo.json', { type: 'application/json' }));
    el.files = transfer.files; el.dispatchEvent(new Event('change', { bubbles: true }));
  }, JSON.stringify(invalid));
  check('invalid tempo import preserves active project', JSON.stringify((await exportProject()).track.tempo) === JSON.stringify(saved.track.tempo));
  await region.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/desktop.png` });
  await page.setViewportSize({ width: 800, height: 600 });
  await region.scrollIntoViewIfNeeded();
  check('compact controls remain inside viewport', await region.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth; }));
  await input('Tempo BPM').focus(); await page.keyboard.press('Tab');
  check('keyboard reaches first-beat input', await input('Tempo first beat seconds').evaluate(el => el === document.activeElement));
  await page.screenshot({ path: `${output}/compact.png` });
  await page.waitForTimeout(900);
  await page.reload();
  await button('Open project editor').click();
  await input('Tempo BPM').waitFor();
  check('refresh restores tempo without original song', Number(await input('Tempo BPM').inputValue()) === 120 && Number(await input('Tempo first beat seconds').inputValue()) === .25);
  check('saved tempo remains editable without song', await button('Save music tempo').isEnabled() && await button('Use playhead as first beat').isDisabled());
  await button('Close project editor').click();
  await input('Restore original project song').setInputFiles('output/playwright/music-analysis-energy-change.wav');
  await button('Play').waitFor();
  await button('Open project editor').click();
  check('matching song restoration retains tempo', (await exportProject()).track.tempo.bpm === 120);
  await button('Close project editor').click();
  await page.locator('#music-file-input').setInputFiles('output/playwright/music-analysis-replacement.wav');
  await button('Play').waitFor();
  await button('Open project editor').click();
  check('song replacement clears tempo', (await exportProject()).track.tempo === undefined && await button('Snap selected cue to beat').isDisabled());
  await input('Tempo BPM').fill('200');
  await button('Create project').click();
  check('project switch clears unsaved tempo draft', await input('Tempo BPM').inputValue() === '');
  check('no unhandled browser errors', errors.length === 0);
  const report = { status: 'passed', browser, checks, errors, screenshots: [`${output}/desktop.png`, `${output}/compact.png`] };
  const pending = page.waitForEvent('download');
  await page.evaluate(report => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' }));
    const link = document.createElement('a'); link.href = url; link.download = 'tempo-report.json'; link.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  }, report);
  await (await pending).saveAs(`${output}/report.json`);
  return report;
}
